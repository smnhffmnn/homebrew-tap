  homepage "https://github.com/smnhffmnn/mux"
  version "0.42.0"
  license "MIT"

  depends_on :macos
  depends_on arch: :arm64

  url "https://github.com/smnhffmnn/mux/releases/download/v0.42.0/mux_0.42.0_darwin_arm64.tar.gz"
  sha256 "ce13de488e7c260db72803f28a3c7ca208e2d0d05b09bc44ddc093e9945758a3"

  def install
    bin.install "mux"
  end

  test do
    assert_match "mux", shell_output("#{bin}/mux --version", 0)
  end
end
