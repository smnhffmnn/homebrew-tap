  version "0.47.0"
  license "MIT"

  depends_on :macos
  depends_on arch: :arm64

  url "https://github.com/smnhffmnn/mux/releases/download/v0.47.0/mux_0.47.0_darwin_arm64.tar.gz"
  sha256 "c3f3f9f8549011c7c1f43368b0b351d64283bdba742dfc04cc395151fa77efd7"

  def install
    bin.install "mux"
  end

  test do
    assert_match "mux", shell_output("#{bin}/mux --version", 0)
  end
end
